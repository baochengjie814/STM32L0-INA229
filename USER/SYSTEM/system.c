#include "system.h"

/*===========================================================================
 * 数学工具
 *===========================================================================*/

/**
 * @brief  取绝对值 (32-bit)
 */
u32 myabs(long int a)
{
    u32 temp;
    if (a < 0) temp = -a;
    else       temp =  a;
    return temp;
}

/*===========================================================================
 * 串口重定向 (printf → USART2)
 *===========================================================================*/

int fputc(int ch, FILE *f)
{
    uint8_t temp[1] = {ch};
    HAL_UART_Transmit(&huart2, temp, 1, 2);
    return ch;
}
